const norm = (s) => String(s).replace(/["'״׳]/g, "").replace(/\s+/g, " ").trim();
// ארוך קודם, כדי ש"קריית ים" לא יזוהה כ"ים"
const NAMES = [...new Set(EXTRA)].sort((a, b) => norm(b).length - norm(a).length);
const SPOKEN = { "זכרון יעקב": "זיכרון יעקב", "יוקנעם": "יקנעם", "קרית": "קריית" };

/** יישובים לפי סדר הופעתם בטקסט, עם מ/ל לפני השם */
export function findExtraPlaces(text) {
  const clean = ` ${norm(text).replace(/[^\p{L}\p{N}\s]/gu, " ").replace(/\s+/g, " ")} `;
  const found = [];
  const taken = [];
  for (const name of NAMES) {
    const n = norm(name);
    const re = new RegExp(`\\s([ומלב]{0,2})${n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?=\\s)`, "g");
    for (const m of clean.matchAll(re)) {
      const start = m.index + 1;
      const end = start + m[0].length - 1;
      if (taken.some(([a, b]) => start < b && end > a)) continue;
      taken.push([start, end]);
      const city = SPOKEN[n] || n.replace(/^קרית /, "קריית ");
      found.push({ city, at: start, role: m[1].includes("מ") ? "from" : m[1].includes("ל") ? "to" : null });
    }
  }
  return found.sort((a, b) => a.at - b.at);
}
